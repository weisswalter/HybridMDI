-- ============================================================================
--  anlage <-> artikel, Anlagenfotos — Stand 21.08.2026
--
--  Walters Szenario: aus einer Charge Artikel werden manche verkauft, manche
--  landen als eigenes Inventar (Anlage). Nach Ablauf der Abschreibung koennen
--  sie wieder verkauft werden. Deshalb eine Beziehung zurueck auf artikel,
--  aber OHNE Constraint - "wir wissen noch nicht, wie die Leute es
--  verwenden werden" (Walter). Ebenso bewusst KEINE automatische Anlage aus
--  einer Lagerentnahme: Schreibmaterial wird auch entnommen und wird dabei
--  nicht zu Anlagevermoegen. Das Anlegen der Anlage bleibt ein eigener,
--  bewusster Schritt.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Beziehung zu artikel — nullable, kein Constraint
-- ---------------------------------------------------------------------------
ALTER TABLE anlage ADD COLUMN IF NOT EXISTS artikel_id integer
  REFERENCES artikel(artikel_id);

COMMENT ON COLUMN anlage.artikel_id IS
  'Herkunft, nicht Ausloeser: dokumentiert nur, aus welchem Artikel diese '
  'Anlage stammt (falls ueberhaupt). Legt die Anlage nicht automatisch an.';

-- ---------------------------------------------------------------------------
-- 2. Anzeige-Sicht: Modul-/Seriennummer und Artikelname aus artikel dazu.
--    Vermeidet FireDAC-Lookup-Felder (die verlangen ALLE Spalten persistent)
--    - stattdessen kommen die zwei Zusatzspalten einfach mit, wenn ueber
--    diese Sicht statt der Tabelle kopiert wird.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_anlage AS
SELECT a.*,
       art.modul_nr           AS artikel_modul_nr,
       art.serien_nr          AS artikel_serien_nr,
       art.artikelname        AS artikel_bezeichnung
  FROM anlage a
  LEFT JOIN artikel art ON art.artikel_id = a.artikel_id;

-- ---------------------------------------------------------------------------
-- 3. Anlagenfotos — eigene Verknuepfungstabelle nach dem Muster von
--    artikel_foto, weil der Ort mitfotografiert sein kann, nicht nur das
--    Stueck selbst.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS anlage_foto (
    foto_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mandant_id   integer NOT NULL REFERENCES mandant(mandant_id),
    anlage_id    integer NOT NULL REFERENCES anlage(anlage_id) ON DELETE CASCADE,
    foto         bytea,
    beschreibung text,
    reihenfolge  integer
);

CREATE INDEX IF NOT EXISTS ix_anlage_foto_anlage   ON anlage_foto(anlage_id);
CREATE INDEX IF NOT EXISTS ix_anlage_foto_mandant  ON anlage_foto(mandant_id);

-- ---------------------------------------------------------------------------
-- 4. fn_anlage_speichern: p_artikel_id ans ENDE angehaengt (Delphi ruft
--    positional auf - eine neue Pflichtstelle in der Mitte wuerde jeden
--    bestehenden Aufruf verschieben).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_anlage_speichern(
    p_anlage_id integer,
    p_mandant_id integer,
    p_bezeichnung character varying,
    p_inventar_nr character varying DEFAULT NULL,
    p_gruppe character varying DEFAULT NULL,
    p_konto_id integer DEFAULT NULL,
    p_aufwand_konto_id integer DEFAULT NULL,
    p_anschaffung_datum date DEFAULT NULL,
    p_anschaffung_wert numeric DEFAULT 0,
    p_restwert numeric DEFAULT 0,
    p_nutzungsdauer_jahre numeric DEFAULT 5,
    p_methode character varying DEFAULT 'linear',
    p_degressiv_prozent numeric DEFAULT NULL,
    p_wiederbeschaffung_wert numeric DEFAULT NULL,
    p_inflation_prozent numeric DEFAULT 0,
    p_kalk_nutzungsdauer_jahre numeric DEFAULT NULL,
    p_kalk_zins_prozent numeric DEFAULT 0,
    p_betriebsstunden_jahr numeric DEFAULT NULL,
    p_unterhalt_jahr numeric DEFAULT 0,
    p_energie_pro_stunde numeric DEFAULT 0,
    p_raum_id integer DEFAULT NULL,
    p_ausser_betrieb_am date DEFAULT NULL,
    p_aktiv boolean DEFAULT true,
    p_bemerkung text DEFAULT NULL,
    p_artikel_id integer DEFAULT NULL
) RETURNS integer AS $$
DECLARE v_id integer;
BEGIN
    INSERT INTO funktion_aufruf (funktion_id, parameter)
    SELECT funktion_id, jsonb_build_array(p_anlage_id, p_mandant_id, p_bezeichnung, p_inventar_nr, p_gruppe, p_konto_id, p_aufwand_konto_id, p_anschaffung_datum, p_anschaffung_wert, p_restwert, p_nutzungsdauer_jahre, p_methode, p_degressiv_prozent, p_wiederbeschaffung_wert, p_inflation_prozent, p_kalk_nutzungsdauer_jahre, p_kalk_zins_prozent, p_betriebsstunden_jahr, p_unterhalt_jahr, p_energie_pro_stunde, p_raum_id, p_ausser_betrieb_am, p_aktiv, p_bemerkung, p_artikel_id)
      FROM funktion WHERE name = 'fn_anlage_speichern';
    IF p_mandant_id IS NULL OR p_mandant_id <= 0 THEN
        RAISE EXCEPTION 'Mandant fehlt.';
    END IF;

    IF COALESCE(p_anlage_id, 0) = 0 THEN
        INSERT INTO anlage (mandant_id, bezeichnung, inventar_nr, gruppe,
            konto_id, aufwand_konto_id, anschaffung_datum, anschaffung_wert,
            restwert, nutzungsdauer_jahre, methode, degressiv_prozent,
            wiederbeschaffung_wert, inflation_prozent, kalk_nutzungsdauer_jahre,
            kalk_zins_prozent, betriebsstunden_jahr, unterhalt_jahr,
            energie_pro_stunde, raum_id, ausser_betrieb_am, aktiv, bemerkung,
            artikel_id)
        VALUES (p_mandant_id, p_bezeichnung, p_inventar_nr, p_gruppe,
            p_konto_id, p_aufwand_konto_id, p_anschaffung_datum,
            p_anschaffung_wert, p_restwert, p_nutzungsdauer_jahre, p_methode,
            p_degressiv_prozent, p_wiederbeschaffung_wert, p_inflation_prozent,
            p_kalk_nutzungsdauer_jahre, p_kalk_zins_prozent,
            p_betriebsstunden_jahr, p_unterhalt_jahr, p_energie_pro_stunde,
            p_raum_id, p_ausser_betrieb_am, COALESCE(p_aktiv, true),
            p_bemerkung, p_artikel_id)
        RETURNING anlage_id INTO v_id;
    ELSE
        UPDATE anlage SET
            bezeichnung = p_bezeichnung, inventar_nr = p_inventar_nr,
            gruppe = p_gruppe, konto_id = p_konto_id,
            aufwand_konto_id = p_aufwand_konto_id,
            anschaffung_datum = p_anschaffung_datum,
            anschaffung_wert = p_anschaffung_wert, restwert = p_restwert,
            nutzungsdauer_jahre = p_nutzungsdauer_jahre, methode = p_methode,
            degressiv_prozent = p_degressiv_prozent,
            wiederbeschaffung_wert = p_wiederbeschaffung_wert,
            inflation_prozent = p_inflation_prozent,
            kalk_nutzungsdauer_jahre = p_kalk_nutzungsdauer_jahre,
            kalk_zins_prozent = p_kalk_zins_prozent,
            betriebsstunden_jahr = p_betriebsstunden_jahr,
            unterhalt_jahr = p_unterhalt_jahr,
            energie_pro_stunde = p_energie_pro_stunde, raum_id = p_raum_id,
            ausser_betrieb_am = p_ausser_betrieb_am,
            aktiv = COALESCE(p_aktiv, true), bemerkung = p_bemerkung,
            artikel_id = p_artikel_id
         WHERE anlage_id = p_anlage_id AND mandant_id = p_mandant_id
        RETURNING anlage_id INTO v_id;
        IF v_id IS NULL THEN
            RAISE EXCEPTION 'Anlage % gibt es fuer Mandant % nicht.',
                            p_anlage_id, p_mandant_id;
        END IF;
    END IF;
    RETURN v_id;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- 5. Foto-Schreibwege — Kopie von fn_artikel_foto_speichern/loeschen,
--    anlage statt artikel.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_anlage_foto_speichern(
    p_mandant_id integer,
    p_anlage_id integer,
    p_foto_id integer DEFAULT NULL,
    p_foto bytea DEFAULT NULL,
    p_beschreibung text DEFAULT NULL,
    p_reihenfolge integer DEFAULT NULL
) RETURNS integer AS $$
DECLARE
    v_id integer;
BEGIN
    INSERT INTO funktion_aufruf (funktion_id, parameter)
    SELECT funktion_id,
           jsonb_build_array(p_mandant_id, p_anlage_id, p_foto_id,
                             '<bytea ' || COALESCE(octet_length(p_foto), 0)::text
                                       || ' Bytes>',
                             p_beschreibung, p_reihenfolge)
      FROM funktion WHERE name = 'fn_anlage_foto_speichern';

    IF COALESCE(p_mandant_id, 0) <= 0 THEN
        RAISE EXCEPTION 'Mandant fehlt.';
    END IF;
    IF COALESCE(p_anlage_id, 0) <= 0 THEN
        RAISE EXCEPTION 'Ohne Anlage kein Foto.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM anlage
                    WHERE anlage_id = p_anlage_id
                      AND mandant_id = p_mandant_id) THEN
        RAISE EXCEPTION 'Anlage % gehoert nicht zu Mandant %.',
                        p_anlage_id, p_mandant_id;
    END IF;

    IF COALESCE(p_foto_id, 0) = 0 THEN
        INSERT INTO anlage_foto (mandant_id, anlage_id, foto,
                                 beschreibung, reihenfolge)
        VALUES (p_mandant_id, p_anlage_id, p_foto, p_beschreibung,
                COALESCE(p_reihenfolge,
                         (SELECT COALESCE(MAX(reihenfolge), 0) + 1
                            FROM anlage_foto
                           WHERE anlage_id = p_anlage_id)))
        RETURNING foto_id INTO v_id;
    ELSE
        UPDATE anlage_foto
           SET beschreibung = p_beschreibung,
               reihenfolge  = COALESCE(p_reihenfolge, reihenfolge),
               foto         = COALESCE(p_foto, foto)
         WHERE foto_id    = p_foto_id
           AND mandant_id = p_mandant_id
           AND anlage_id  = p_anlage_id
        RETURNING foto_id INTO v_id;

        IF v_id IS NULL THEN
            RAISE EXCEPTION 'Foto % gehoert nicht zu Anlage %.',
                            p_foto_id, p_anlage_id;
        END IF;
    END IF;

    RETURN v_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_anlage_foto_loeschen(
    p_foto_id integer,
    p_mandant_id integer
) RETURNS void AS $$
DECLARE
    v_anzahl integer;
BEGIN
    INSERT INTO funktion_aufruf (funktion_id, parameter)
    SELECT funktion_id, jsonb_build_array(p_foto_id, p_mandant_id)
      FROM funktion WHERE name = 'fn_anlage_foto_loeschen';

    DELETE FROM anlage_foto
     WHERE foto_id = p_foto_id AND mandant_id = p_mandant_id;
    GET DIAGNOSTICS v_anzahl = ROW_COUNT;

    IF v_anzahl = 0 THEN
        RAISE EXCEPTION 'Foto % gibt es fuer Mandant % nicht.',
                        p_foto_id, p_mandant_id;
    END IF;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- 6. Funktionskatalog
-- ---------------------------------------------------------------------------
INSERT INTO funktion (name, parameterliste)
VALUES
  ('fn_anlage_speichern',
   'p_anlage_id integer, p_mandant_id integer, p_bezeichnung varchar, ... , p_artikel_id integer'),
  ('fn_anlage_foto_speichern',
   'p_mandant_id integer, p_anlage_id integer, p_foto_id integer, p_foto bytea, p_beschreibung text, p_reihenfolge integer'),
  ('fn_anlage_foto_loeschen',
   'p_foto_id integer, p_mandant_id integer')
ON CONFLICT (name) DO UPDATE SET parameterliste = EXCLUDED.parameterliste;

INSERT INTO funktion_tabelle (funktion_id, tabelle, wirkung, ueber)
SELECT f.funktion_id, v.tabelle, v.wirkung, 'direkt'
  FROM funktion f
  CROSS JOIN (VALUES ('funktion_aufruf', 'INSERT'),
                      ('anlage_foto', 'INSERT'),
                      ('anlage_foto', 'UPDATE'),
                      ('anlage_foto', 'DELETE')) AS v(tabelle, wirkung)
 WHERE f.name IN ('fn_anlage_foto_speichern', 'fn_anlage_foto_loeschen')
   AND ((f.name = 'fn_anlage_foto_speichern' AND v.wirkung IN ('INSERT','UPDATE') AND v.tabelle IN ('funktion_aufruf','anlage_foto'))
        OR (f.name = 'fn_anlage_foto_loeschen' AND ((v.tabelle = 'funktion_aufruf' AND v.wirkung = 'INSERT') OR (v.tabelle = 'anlage_foto' AND v.wirkung = 'DELETE'))))
ON CONFLICT (funktion_id, tabelle, wirkung) DO NOTHING;

INSERT INTO funktion_tabelle (funktion_id, tabelle, wirkung, ueber)
SELECT f.funktion_id, 'anlage', 'UPDATE', 'direkt'
  FROM funktion f WHERE f.name = 'fn_anlage_speichern'
ON CONFLICT (funktion_id, tabelle, wirkung) DO NOTHING;
INSERT INTO funktion_tabelle (funktion_id, tabelle, wirkung, ueber)
SELECT f.funktion_id, 'anlage', 'INSERT', 'direkt'
  FROM funktion f WHERE f.name = 'fn_anlage_speichern'
ON CONFLICT (funktion_id, tabelle, wirkung) DO NOTHING;
INSERT INTO funktion_tabelle (funktion_id, tabelle, wirkung, ueber)
SELECT f.funktion_id, 'funktion_aufruf', 'INSERT', 'direkt'
  FROM funktion f WHERE f.name = 'fn_anlage_speichern'
ON CONFLICT (funktion_id, tabelle, wirkung) DO NOTHING;
